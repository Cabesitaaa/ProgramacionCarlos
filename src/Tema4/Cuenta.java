package Tema4;
public class Cuenta {
    int numeroCuenta;
    int saldoDisponible;

    public Cuenta(int numeroCuenta, int saldoDisponible) {
        this.numeroCuenta = numeroCuenta;
        this.saldoDisponible = saldoDisponible;
    }
    public Cuenta() {
        this.numeroCuenta = 0;
        this.saldoDisponible = 0;
    }
}
